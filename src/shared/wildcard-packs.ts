/** Re-adding an unchanged pack reuses its list; occupied names and edited copies are preserved. */
export function stageWildcardPack(
  entries: Record<string, string[]>,
  id: string,
): { entries: Record<string, string[]>; name: string; added: boolean } {
  const pack = WILDCARD_PACKS.find(p => p.id === id);
  if (!pack) throw Error('Choose an available starter pack.');
  const prefix = `starter_${pack.id}`;
  for (const [name, values] of Object.entries(entries))
    if ((name === prefix || name.startsWith(prefix + '_')) && JSON.stringify(values) === JSON.stringify(pack.entries))
      return { entries: structuredClone(entries), name, added: false };
  let name = prefix,
    index = 2;
  while (Object.hasOwn(entries, name)) name = `${prefix}_${index++}`;
  const count = Object.values(entries).reduce((total, values) => total + values.length, 0) + pack.entries.length;
  if (count > DYNAMIC_PROMPT_LIMITS.dictionaryEntries)
    throw Error(
      `Adding this pack would go over the ${DYNAMIC_PROMPT_LIMITS.dictionaryEntries.toLocaleString('en-US')}-choice limit. Remove lists you don't use first.`,
    );
  return { entries: { ...structuredClone(entries), [name]: [...pack.entries] }, name, added: true };
}

