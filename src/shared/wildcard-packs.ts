export function cleanSpeciesPreset(entries: Record<string, string[]>): Record<string, string[]> {
  return Object.fromEntries(
    Object.entries(entries).map(([name, values]) => {
      if (!/^starter_species(?:_\d+)?$/.test(name)) return [name, [...values]];
      const cleaned = values.filter(value => !RETIRED_SPECIES_TAGS.has(value));
      return [name, cleaned.length ? cleaned : [...WILDCARD_PACKS.find(pack => pack.id === 'species')!.entries]];
    }),
  );
}
