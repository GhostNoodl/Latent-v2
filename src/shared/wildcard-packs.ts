import { DYNAMIC_PROMPT_LIMITS } from './dynamic-prompts';
/** tags: booru-style tags for SDXL models. mix: lists built from other lists. plain: sentences for newer models. */
export type WildcardPackGroup = 'tags' | 'mix' | 'plain';
export interface WildcardPack {
  id: string;
  name: string;
  description: string;
  group: WildcardPackGroup;
  entries: readonly string[];
  source: { label: string; url?: string };
  reviewed: string;
}
/** Normalize bundled vocabulary only. Never rewrite or deduplicate authored lists, where repetition may be intentional weighting. */
export function cleanPackEntries(values: readonly string[], aliases: Readonly<Record<string, string>> = {}): string[] {
  const result = new Set<string>();
  for (const value of values) {
    let tag = value.trim().toLowerCase().replace(/\s+/g, '_');
    tag = aliases[tag] ?? tag;
    const text = tag.replace(/_/g, ' ').trim();
    if (text) result.add(text);
  }
  return [...result];
}
const make = (
  id: string,
  name: string,
  description: string,
  values: string,
  source: WildcardPack['source'],
  aliases: Record<string, string> = {},
): WildcardPack => ({
  id,
  name,
  description,
  group: 'tags',
  entries: cleanPackEntries(values.split('|'), aliases),
  source,
  reviewed: '2026-09-14',
});
const LATENT = { label: 'Written for Latent' };
/** Common booru-style prompt tags, picked by hand for Latent. */
const tags = (id: string, name: string, description: string, values: string): WildcardPack => ({
  ...make(id, name, description, values, { label: 'Written for Latent, using common booru-style tags' }),
  reviewed: '2026-11-26',
});
